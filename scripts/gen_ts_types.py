"""Generate the TypeScript SDK's wire-contract types from `wyrd-spec`.

The Rust `wyrd-spec` types are the single source. `mise run codegen:regen`
pipes the transient contract bundle printed by
`cargo run -p wyrd-spec --example gen_schemas --features server -- contracts`
into this script, which keeps the Card envelopes the SDK types
(`SUPPORTED_KINDS`), the wire roots the SDK exposes (`WIRE_ROOTS`), and every
definition those reach, and writes one TypeScript module. It is a generated
output: `mise run codegen:check` regenerates it and fails on drift.

Schemas are lowered to a small intermediate form first. Inline object schemas
(tagged-union variants, nested properties) are hoisted into named types, and
an object with shared properties plus `oneOf` variants becomes one merged
object per variant. A schema that admits any JSON value lowers to `JsonValue`;
any other construct the lowering does not understand stops generation with a
diagnostic naming its owner instead of silently widening a known contract.
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TS_OUT = ROOT / "sdks/wyrd-sdk-ts/wyrd/src/card-types.ts"

# Card kinds whose envelopes are typed; every other kind stays untyped until
# it is implemented and tested.
SUPPORTED_KINDS = [
    "Data",
    "Model",
    "Prompt",
    "Agent",
    "Verifier",
    "Service",
    "Trigger",
    "Operator",
]

# Bundle roots, by Rust type name, whose wire contracts the SDK exposes. Each
# is emitted under its schema name with everything it reaches; `src/index.ts`
# re-exports them under their public SDK names.
