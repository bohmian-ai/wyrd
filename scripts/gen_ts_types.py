# Wire roots the SDK sends. Every definition reachable from one of these or
# from the Card envelope keeps input optionality; every other definition is
# only read from a response, so a field the server always serializes is required.
# `AlterTableRequest` stays out: it reaches `FieldSpec`, which `BifrostTableDescription`
# returns, and its own optional fields stay optional in output mode.
REQUEST_ROOTS = {
    "BifrostQueryRequest",
    "CreateOperatorConnectionRequest",
    "CreateServicePrincipalRequest",
    "GatewayCapturePolicyWrite",
    "GatewayFallbackPolicy",
    "GatewayGovernancePolicy",
    "ListCardsRequest",
    "PrincipalQuery",
    "ProviderDeployment",
    "RevokePrincipalRequest",
    "UpdateOperatorConnectionRequest",
}

# Property extension carrying the schema of the value an omitted-when-`None`
# field holds whenever it is serialized (`wyrd_spec::schema::skipped_option`).
SERIALIZED = "x-wyrd-serialized"

HEADER = "Generated by `mise run codegen:regen` from `wyrd-spec` contract types. Do not edit."

# Any JSON value; what an opaque (`true` or keyword-free) schema admits.
JSON_VALUE = (
    "export type JsonValue =\n"
    "  | string\n"
    "  | number\n"
    "  | boolean\n"
    "  | null\n"
    "  | readonly JsonValue[]\n"
    "  | { readonly [key: string]: JsonValue };"
)

# Keywords that constrain a schema's shape. A schema without any of them is
# opaque JSON; annotations such as `description`, `default`, `format`, and
# numeric or length bounds refine a shape without changing its TypeScript type.
SHAPE_KEYWORDS = {
    "$ref",
    "additionalProperties",
    "allOf",
    "anyOf",
    "const",
    "enum",
    "items",
    "oneOf",
    "properties",
    "type",
}

# Intermediate type expressions:
#   ("ref", name) | ("prim", kind) | ("lit", value) | ("array", t) | ("map", t)
#   | ("union", [t, ...])
# Named nodes:
#   ("object", [(key, t, required, description)], description)
#   | ("alias", t, description)


def pascal(text: str) -> str:
    """Return `text` as a PascalCase identifier fragment."""
    return "".join(
        part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", text) if part
    )


class Lowering:
    """Lower JSON Schema definitions into named intermediate nodes."""

    def __init__(self, definitions: dict, inputs: set[str]) -> None:
        self.definitions = definitions
        self.inputs = inputs
        self.output = False
        self.nodes: dict[str, tuple] = {}
        self.pending: list[str] = []

    def require(self, name: str) -> str:
        """Queue a referenced definition for lowering and return its name."""
        if name not in self.definitions:
            raise SystemExit(
                f"{name}: referenced definition is missing from the contract bundle"
            )
        if name not in self.nodes and name not in self.pending:
            self.pending.append(name)
        return name

    def drain(self) -> None:
        """Lower every queued definition, including definitions they reach."""
        while self.pending:
            name = self.pending.pop()
            if name not in self.nodes:
                self.define(name, self.definitions[name])

    def fresh(self, name: str) -> str:
        """Return a hoisted-type name that collides with no definition."""
        candidate, index = name, 2
        while candidate in self.nodes or candidate in self.definitions:
            candidate, index = f"{name}{index}", index + 1
        return candidate

    def define(self, name: str, schema: dict) -> None:
        """Lower one schema into the named node `name`.

        A definition outside `inputs` is lowered in output mode: schemars
        writes `default` only for a field serde always serializes, so that
        field is required in what the server returns, and a field serde skips
        when `None` lowers its `SERIALIZED` schema, the value it holds when present.
        """
        self.output = name not in self.inputs
        description = schema.get("description")
        if self.is_object(schema) and not self.variants(schema):
            self.nodes[name] = ("object", [], description)
            self.nodes[name] = ("object", self.properties(name, schema), description)
        else:
            self.nodes[name] = ("alias", None, description)
            self.nodes[name] = ("alias", self.expr(name, schema), description)

    @staticmethod
    def variants(schema: dict) -> list:
        """Return a schema's `oneOf`/`anyOf` alternatives."""
        return schema.get("oneOf") or schema.get("anyOf") or []

    @staticmethod
    def is_object(schema: dict) -> bool:
        """Report whether a schema declares an object with named properties."""
        return "properties" in schema and schema.get("type", "object") == "object"

    def properties(self, owner: str, schema: dict, shared: dict | None = None) -> list:
        """Lower an object's properties, merging a union's `shared` properties."""
        shared = shared or {}
        extra = schema.get("additionalProperties", False)
        if extra not in (True, False):
            raise SystemExit(
                f"{owner}: object with both properties and typed additionalProperties"
            )
        base = self.referenced(schema)
        merged = {
            **shared.get("properties", {}),
            **base.get("properties", {}),
            **schema.get("properties", {}),
        }
        required = (
            set(schema.get("required", []))
            | set(base.get("required", []))
            | set(shared.get("required", []))
        )
        if self.output:
            required |= {
                key
                for key, value in merged.items()
                if isinstance(value, dict) and "default" in value
            }
        return [
            (
                key,
                self.expr(owner + pascal(key), self.serialized(value)),
                key in required,
                value.get("description") if isinstance(value, dict) else None,
            )
            for key, value in sorted(merged.items())
        ]

    def referenced(self, schema: dict) -> dict:
        """Return the object a `$ref` beside an object's own properties names.

        An internally tagged newtype variant is the tag property next to a
        `$ref` to the wrapped struct, whose properties the variant also has.
        """
        if "$ref" not in schema or "properties" not in schema:
            return {}
        return self.definitions[schema["$ref"].split("/")[-1]]

    def serialized(self, schema: dict | bool) -> dict | bool:
        """Return a property's schema as lowered in the current mode."""
        if self.output and isinstance(schema, dict) and SERIALIZED in schema:
            return schema[SERIALIZED]
        return schema

    def hoist(self, name: str, schema: dict, shared: dict | None = None) -> tuple:
        """Name one inline object schema and return a reference to it."""
        if "properties" not in schema:
            raise SystemExit(
                f"{name}: union variant sharing properties is not an inline object"
            )
        name = self.fresh(name)
        self.nodes[name] = ("object", [], schema.get("description"))
        self.nodes[name] = (
            "object",
            self.properties(name, schema, shared),
            schema.get("description"),
        )
        return ("ref", name)

    @staticmethod
    def tag(schema: dict) -> str | None:
        """Return the single-value `const` or `enum` tag that names a union variant."""
        for value in schema.get("properties", {}).values():
            if isinstance(value, dict) and "const" in value:
                return value["const"]
            if isinstance(value, dict) and len(value.get("enum", [])) == 1:
                return value["enum"][0]
        return None

    def expr(self, owner: str, schema: dict | bool) -> tuple:
        """Lower one schema position into a type expression.

        Raises `SystemExit` naming `owner` for a construct the lowering does
        not model, so an unsupported contract fails generation instead of
        widening to `JsonValue`.
        """
        if schema is True or (
            isinstance(schema, dict) and not SHAPE_KEYWORDS & schema.keys()
        ):
            return ("prim", "any")
        if not isinstance(schema, dict):
            raise SystemExit(f"{owner}: unsupported schema {schema!r}")
        if "$ref" in schema and not self.is_object(schema):
            return ("ref", self.require(schema["$ref"].split("/")[-1]))
        if "allOf" in schema:
            if len(schema["allOf"]) != 1:
                raise SystemExit(
                    f"{owner}: allOf with more than one member is not supported"
                )
            return self.expr(owner, schema["allOf"][0])
        variants = self.variants(schema)
        if variants:
            shared = schema if "properties" in schema else None
            members = []
            for index, variant in enumerate(variants, start=1):
                if shared is not None or self.is_object(variant):
                    keys = list(variant.get("properties", {}))
                    label = self.tag(variant) or (
                        keys[0] if len(keys) == 1 else f"Variant{index}"
                    )
                    members.append(self.hoist(owner + pascal(label), variant, shared))
                else:
                    members.append(self.expr(f"{owner}Variant{index}", variant))
            return ("union", members)
        if "const" in schema:
            return ("lit", schema["const"])
        if "enum" in schema:
            return ("union", [("lit", value) for value in schema["enum"]])
        kinds = schema.get("type")
        if isinstance(kinds, list):
            return (
                "union",
                [self.expr(owner, {**schema, "type": kind}) for kind in kinds],
            )
        if kinds == "array":
            items = schema.get("items", True)
            if isinstance(items, list):
                raise SystemExit(f"{owner}: tuple-form array items are not supported")
            return ("array", self.expr(owner + "Item", items))
        if kinds == "object" or (kinds is None and "properties" in schema):
            if schema.get("properties"):
                return self.hoist(owner, schema)
            extra = schema.get("additionalProperties", True)
            if extra is False:
                raise SystemExit(
                    f"{owner}: closed object without properties is not supported"
                )
            return ("map", self.expr(owner + "Value", extra))
        if kinds in ("string", "integer", "number", "boolean", "null"):
            return ("prim", kinds)
        raise SystemExit(
            f"{owner}: unsupported schema {json.dumps(schema, sort_keys=True)}"
        )


def flatten(expr: tuple) -> list[tuple]:
    """Flatten nested unions into one de-duplicated member list."""
    if expr[0] != "union":
        return [expr]
    members: list[tuple] = []
    for member in expr[1]:
        for flat in flatten(member):
            if flat not in members:
                members.append(flat)
    return members


class TypeScript:
    """Render intermediate nodes as TypeScript declarations."""

    PRIMS = {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
        "any": "JsonValue",
    }

    def expr(self, expr: tuple) -> str:
        """Render one type expression."""
        tag = expr[0]
        if tag == "ref":
            return expr[1]
        if tag == "prim":
            return self.PRIMS[expr[1]]
        if tag == "lit":
            return json.dumps(expr[1])
        if tag == "array":
            inner = self.expr(expr[1])
            wrap = " | " in inner or inner.startswith("readonly ")
            return f"readonly ({inner})[]" if wrap else f"readonly {inner}[]"
        if tag == "map":
            return f"Readonly<Record<string, {self.expr(expr[1])}>>"
        return " | ".join(dict.fromkeys(self.expr(member) for member in flatten(expr)))

    @staticmethod
    def doc(description: str | None, indent: str) -> list[str]:
        """Render a JSDoc block."""
        if not description:
            return []
        lines = description.replace("*/", "*\\/").splitlines()
        return [
            f"{indent}/**",
            *[f"{indent} * {line}".rstrip() for line in lines],
            f"{indent} */",
        ]

    def render(self, nodes: dict[str, tuple]) -> str:
        """Render the complete TypeScript module."""
        out = [f"// {HEADER}", "", "/** Any value JSON can carry. */", JSON_VALUE, ""]
        for name in sorted(nodes):
            node = nodes[name]
            out.extend(self.doc(node[-1], ""))
            if node[0] == "alias":
                out.append(f"export type {name} = {self.expr(node[1])};")
            else:
                out.append(f"export interface {name} {{")
                for key, expr, required, description in node[1]:
                    out.extend(self.doc(description, "  "))
                    optional = "" if required else "?"
                    out.append(f"  readonly {key}{optional}: {self.expr(expr)};")
                out.append("}")
            out.append("")
        return "\n".join(out)


def reachable(definitions: dict, names: list[str]) -> set[str]:
    """Return `names` and every definition their schemas reference."""
    seen: set[str] = set()
    stack = list(names)
    while stack:
        name = stack.pop()
        if name in seen:
            continue
        seen.add(name)
        stack.extend(
            ref.split("/")[-1]
            for ref in re.findall(r'"\$ref": "([^"]+)"', json.dumps(definitions[name]))
        )
    return seen


def target(roots: dict, root: str) -> str:
    """Return the definition name a registered wire root refers to."""
    if root not in roots:
        raise SystemExit(
            f"{root}: wire root is not registered in gen_schemas `contracts`"
        )
    ref = roots[root].get("$ref")
    if ref is None:
        raise SystemExit(f"{root}: wire root schema is inline, not a named definition")
    return ref.split("/")[-1]


def envelope(
    lowering: Lowering,
    schema: dict,
    name: str,
    kind: tuple,
    spec: tuple,
    description: str,
) -> None:
    """Add one Card envelope node whose `kind` and `spec` are narrowed."""
    properties = schema["properties"]
    fields = []
    for key in sorted(properties):
        expr = {"kind": kind, "spec": spec}.get(key) or lowering.expr(
            name + pascal(key), properties[key]
        )
        fields.append(
            (key, expr, key in schema["required"], properties[key].get("description"))
        )
    lowering.nodes[name] = ("object", fields, description)


def lower(bundle: dict) -> dict[str, tuple]:
    """Lower the supported Card envelopes, the wire roots, and everything they reach.

    Each supported kind gets `Registered<Kind>Card` with its typed spec. Every
    other kind gets an envelope whose spec stays a JSON map, grouped as
    `RegisteredUntypedCard`, so `RegisteredCard` covers every envelope the registry can return while
    exposing typed specs only for the supported kinds.
    """
    definitions = bundle["$defs"]
    roots = bundle["roots"]
    requests = [target(roots, root) for root in sorted(REQUEST_ROOTS)]
    lowering = Lowering(definitions, reachable(definitions, ["Card", *requests]))
    schema = definitions["Card"]
    names = []
    for kind in SUPPORTED_KINDS:
        name = f"Registered{kind}Card"
        spec = ("ref", lowering.require(f"{kind}Spec"))
        envelope(
            lowering,
            schema,
            name,
            ("lit", kind),
            spec,
            f"Registered `{kind}` Card envelope.",
        )
        names.append(("ref", name))
    deferred = [
        kind for kind in definitions["CardKind"]["enum"] if kind not in SUPPORTED_KINDS
    ]
    # One envelope per deferred kind keeps every `kind` a single literal, so
    # `card["kind"] == "Data"` narrows the `RegisteredCard` union in checkers
    # that only discriminate on single-literal tags.
    untyped = []
    for kind in deferred:
        name = f"Registered{kind}Card"
        envelope(
            lowering,
            schema,
            name,
            ("lit", kind),
            ("map", ("prim", "any")),
            f"Registered `{kind}` Card envelope; its spec is not typed yet.",
        )
        untyped.append(("ref", name))
    lowering.nodes["RegisteredUntypedCard"] = (
        "alias",
        ("union", untyped),
        "Registered Card envelope of a kind whose spec is not typed yet.",
    )
    names.append(("ref", "RegisteredUntypedCard"))
    lowering.nodes["TypedCardKind"] = (
        "alias",
        ("union", [("lit", kind) for kind in SUPPORTED_KINDS]),
        "Card kinds whose `spec` and `status` `cards.get` types.",
    )
    lowering.nodes["RegisteredCard"] = (
        "alias",
        ("union", names),
        "One registered Card envelope as `cards.get` returns it, discriminated by `kind`.",
    )
    for root in WIRE_ROOTS:
        lowering.require(target(roots, root))
    lowering.drain()
    return lowering.nodes


def main() -> None:
    """Write the generated TypeScript module from the bundle on stdin."""
    nodes = lower(json.load(sys.stdin))
    TS_OUT.write_text(TypeScript().render(nodes), encoding="utf-8")
    print(f"Wrote {len(nodes)} wire types to {TS_OUT}", file=sys.stderr)


if __name__ == "__main__":
    main()
